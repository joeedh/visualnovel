/**
 * Bundle the web exporter into one self-contained file: `apps/desktop/dist/main/vn-site.mjs`.
 *
 * The desktop app writes this file into an author's project repo, where a GitHub Actions runner
 * executes it with plain node. That is why it has no externals and no dependencies — CI does no
 * install, and the project repo has no `node_modules`.
 *
 * It lands beside `dist/main/index.cjs` so `join(__dirname, 'vn-site.mjs')` finds it in a
 * checkout and in a packaged build alike; `package.desktop.mjs` copies `dist/` wholesale.
 *
 * Neither minified nor sourcemapped, deliberately: the output is committed to someone's
 * repository, so it should diff as ordinary lines.
 *
 * `esbuild.desktop.mjs` imports the options below so the dev watcher and `pnpm build:main` both
 * produce it. Running this file directly builds it once.
 */
import { build } from 'esbuild';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { alias, REPO_ROOT as root } from './aliases.mjs';

export const sitebuilderOptions = {
  entryPoints: [resolve(root, 'packages/export/src/site-cli.ts')],
  outfile: resolve(root, 'apps/desktop/dist/main/vn-site.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  sourcemap: false,
  minify: false,
  alias,
  banner: {
    js:
      '// Generated by VN Studio (scripts/esbuild.sitebuilder.mjs). Do not edit.\n' +
      '// Renders vngen/build/story.play.json into a static site. Reinstall to update.' +
      '\n' +
      // The file lands in an author's repository, which may lint everything it contains.
      // Bundled output is not code anybody there wrote, so it opts out rather than being
      // configured out.
      '/* eslint-disable */',
  },
  logLevel: 'info',
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await build(sitebuilderOptions);
}

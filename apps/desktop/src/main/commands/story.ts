export const storyExport = define({
  id: 'story.export',
  title: 'Export playable',
  description: 'Write vngen/build/story.play.json — the `vngen export` equivalent.',
  mutating: true,
  props: {},
  async check(_props, ctx) {
    // Building the playable *is* the question — it is pure and writes nothing, so the check
    // can answer with the real projection rather than a guess about whether one would work.
    const playable = await ctx.host.session.playable();
    const scenes = Object.keys(playable.scenes).length;
    return scenes
      ? { ok: true, note: `${scenes} scene(s) ready to export.` }
      : { ok: false, reason: 'There is no scene to export.' };
  },
  async run(_props, ctx) {
    const { scenes } = await ctx.host.session.exportPlayable();
    return {
      message: `Exported ${scenes} scene(s) to story.play.json.`,
      written: ['vngen/build/story.play.json'],
    };
  },
});

export const storyScreenplay = define({
  id: 'story.screenplay',
  // Named for the format it writes, beside `story.export`'s "Export playable". A menu entry
  // takes its tooltip from this title, so the two must be the same words.
  title: 'Export Fountain',
  description:
    'Project the scenes back into one Fountain screenplay at the project root — the `vngen ' +
    'screenplay` equivalent. A snapshot, not a mirror: it goes stale as soon as a scene changes.',
  mutating: true,
  props: {
    clean: prop.boolean('drop the [[…]] machine markers, which makes the output one-way', {
      default: false,
    }),
  },
  async check(_props, ctx) {
    const graph = await ctx.host.session.storyGraph();
    return graph.scenes.length
      ? { ok: true, note: `${graph.scenes.length} scene(s) ready to write.` }
      : { ok: false, reason: 'There is no scene to write.' };
  },
  async run({ clean }, ctx) {
    const result = await ctx.host.session.writeScreenplay(clean);
    if (!result.ok) throw new Error(result.message);
    return { message: result.message, written: result.written };
  },
});

/**
 * The story as commands: read the branch graph, rewire it, and write the prose.
 *
 * Every mutating command here follows the same path — a pure decision, then the one session
 * method that owns that write. A rewire is `branchops` + `session.editBranches`, which patches
 * the branch markers in whichever file each scene lives in — one `scenes/<id>.md` chunk, or the
 * whole screenplay. A prose edit is `lineops` + `session.editScene`, which re-serializes each
 * changed scene whole and can add or remove a chunk. Nothing else in the app writes either, so
 * one authorial act is one `CommandRecord` with one replayable invocation.
 *
 * The rewires, the prose edits, `setCoverage` and `assignLineIds` are `undoable`: they write
 * scene files and `work/shots/*.json`, which are documents. `story.export` and `story.screenplay`
 * are not — `story.play.json` and the projected screenplay are generated output, regenerated by
 * re-running the command.
 */

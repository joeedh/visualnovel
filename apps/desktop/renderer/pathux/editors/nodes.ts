/**
 * The node graph one slot is generated by, drawn as a graph the author edits directly. Task Graph
 * says whether a slot has been drawn; this pane says how it will be.
 *
 * path.ux's view binds its widgets through the data API, and this application has no data API: the
 * graph is read over IPC and written through `gengraph.*` commands. So the view is pointed at an
 * empty graph path, which keeps it from asking the data API for anything, and every mutating
 * gesture is routed into a command by the delegate below. A frame's own prop rows are built from
 * the node instead, in `buildNodeUI`.
 */
export class GenGraphView extends NodeGraphView {
  /** Routes the two edits path.ux has no gesture for, which the node rows raise instead. */
  onGenEdit?: (edit: GenEdit) => void;

  static override define() {
    return { ...NodeGraphView.define(), tagname: 'vn-gengraph-view-x' };
  }

  /**
   * Clears the datapath each frame was stamped with. The path names a graph the data API cannot
   * resolve, so the rows built from it would each read `(unavailable)`; clearing it drops those
   * rows and the inline socket editors, and leaves `buildNodeUI`'s own rows and the socket
   * terminals standing.
   */
  override syncGraph(): void {
    super.syncGraph();
    for (const frame of this.frames.values()) {
      if (frame.nodePath === '') continue;
      frame.nodePath = '';
      frame.syncContents();
    }
  }
}

UIBase.register(GenGraphView);

/** What one gesture would do, weighed against the graph on screen with nothing written. */
type Weighed =
  | { ok: true; edit: GenEdit; decision: GenEditDecision }
  | { ok: false; reason: string };

export class GenGraphEditor extends VnEditor {
  private view!: GenGraphView;
  private notesEl!: HTMLDivElement;
  private emptyEl!: HTMLDivElement;

  /** The graph on screen, which trails `ui.graphSlug` by one read. */
  private graph: Graph | undefined;
  private slug = '';
  /** What the read and the file itself had to say, shown above the canvas. */
  private notes: string[] = [];
  /** Rising with every read, so a slow answer for a graph the pane has left is dropped. */
  private token = 0;

  static override define() {
    return {
      tagname: 'vn-gengraph-editor-x',
      areaname: 'gengraph',
      icon: -1,
    };
  }

  override init() {
    super.init();

    const bar = (this.header as Container).row();
    bar.label('GEN GRAPH').style['padding'] = '0px 8px';
    this.pinToggle(bar);
    describe(
      bar.button('Add…', () => this.view.openAddMenu(ADD_MENU_AT)),
      'Add a node to this graph',
    );
    describe(
      bar.button('Arrange', () => this.view.arrangeNodes()),
      'Lay the whole graph out again, left to right',
    );
    describe(
      bar.button('Delete', () => this.view.deleteSelected()),
      'Remove the selected nodes and sever the selected links',
    );
    describe(
      bar.button('⟳', () => void this.load(this.slug)),
      'Re-read this graph from disk',
    );
    bar.flushUpdate();

    this.adoptStyle(GENGRAPH_CSS);
    const surface = document.createElement('div');
    surface.className = 'gg-surface';

    this.notesEl = document.createElement('div');
    this.notesEl.className = 'gg-notes';
    surface.appendChild(this.notesEl);

    const canvas = document.createElement('div');
    canvas.className = 'gg-canvas';
    this.emptyEl = document.createElement('div');
    this.emptyEl.className = 'gg-empty';
    canvas.appendChild(this.emptyEl);
    surface.appendChild(canvas);
    this.appendSurface(surface);

    this.view = UIBase.createElement('vn-gengraph-view-x') as GenGraphView;
    this.view.parentWidget = this.container;
    canvas.appendChild(this.view);
    this.view.ctx = this.ctx;
    this.view._init();
    this.view.style.flex = '1 1 auto';
    this.view.style.minWidth = '0px';
    this.view.delegate = this.delegate();
    this.view.onGenEdit = (edit) => this.propose(edit);
    // path.ux opens its node menu from a right-click on a frame and offers none for the canvas
    // itself. A right-drag that panned has already had this event swallowed by the pan container.
    this.view.panzoom.addEventListener('contextmenu', (event: MouseEvent) => {
      event.preventDefault();
      const rect = this.view.panzoom.getBoundingClientRect();
      this.view.openAddMenu([event.clientX - rect.x, event.clientY - rect.y]);
    });

    // A command this pane sent is not the only thing that rewrites a graph: the agent's graph tool,
    // an undo and a `gengraph.*` invocation from the palette all reach the same file.
    this.watch(
      () => onInvalidate(() => void this.load(this.slug)),
      () => void this.load(this.slug),
    );

    this.paint();
  }

  override update() {
    super.update();

    const slug = this.ui.graphSlug;
    if (slug !== this.slug) void this.load(slug);
  }

  // -------------------------------------------------------------------------
  // Reading
  // -------------------------------------------------------------------------

  private async load(slug: string): Promise<void> {
    const mine = ++this.token;
    this.slug = slug;

    if (slug === '') {
      this.graph = undefined;
      this.notes = [];
      this.paint();
      return;
    }

    const read = await api.invoke('gengraph:doc', slug);
    if (mine !== this.token) return;

    if (!read.ok) {
      this.graph = undefined;
      this.notes = [read.reason];
    } else {
      const parsed = readGraphFile(read.file);
      this.graph = parsed.graph;
      this.notes = [...parsed.diagnostics, ...read.diagnostics].map((note) => note.message);
    }
    this.paint();
  }

  /**
   * Points the view at what was read, keeping the selection across the reload. Every edit reloads
   * the whole file, so a selection dropped here would be a selection that lasted one gesture.
   */
  private paint(): void {
    const held = [...this.view.selection];
    this.view.setGraph(this.graph, '');
    for (const id of held) {
      if (this.graph?.nodeIdMap.get(id) !== undefined) this.view.selection.add(id);
    }
    this.view.syncGraph();

    this.notesEl.textContent = this.notes.join('\n');
    this.notesEl.style.display = this.notes.length === 0 ? 'none' : 'block';
    this.emptyEl.textContent =
      this.slug === ''
        ? 'Pick a slot a generation graph draws to see the graph here.'
        : this.graph === undefined
          ? ''
          : this.graph.nodes.length === 0
            ? 'This graph has no nodes yet. Right-click the canvas to add one.'
            : '';
  }

  // -------------------------------------------------------------------------
  // Writing
  // -------------------------------------------------------------------------

  private delegate(): NodeGraphDelegate {
    return {
      check: (_ctx, edit): EditVerdict => this.judge(edit),
      perform: (_ctx, edit): void => this.dispatch(edit),
    };
  }

  /** Judges a gesture, and says the refusal that would otherwise leave a drop looking ignored. */
  private judge(edit: GraphEdit): EditVerdict {
    const weighed = this.weigh(edit);
    // A `moveNode` check runs once per frame per pointer move and shows its own refusal by fading
    // the frame, so speaking that one would repeat a sentence hundreds of times in a drag.
    if (!weighed.ok && edit.kind !== 'moveNode') say(weighed.reason, true);
    return weighed.ok ? { ok: true } : { ok: false, reason: weighed.reason };
  }

  private dispatch(edit: GraphEdit): void {
    const weighed = this.weigh(edit);
    if (!weighed.ok) return;
    // A drag is applied to the graph on screen as well as sent, because the view resyncs its frames
    // from `node.pos` the moment this returns and a frame that never moved snaps back.
    if (weighed.edit.op === 'moveNodes') weighed.decision.apply();
    this.send(weighed.edit);
  }

  private weigh(edit: GraphEdit): Weighed {
    const read = genEditFor(edit);
    if (!read.ok) return read;
    if (this.graph === undefined) return { ok: false, reason: 'no generation graph is open here' };

    const decision = decideGenEdit(this.graph, read.edit);
    return decision.ok
      ? { ok: true, edit: read.edit, decision }
      : { ok: false, reason: decision.reason };
  }

  /** Weighs an edit a node's own rows raised, which reaches no path.ux gesture. */
  private propose(edit: GenEdit): void {
    if (this.graph === undefined) return;

    const decision = decideGenEdit(this.graph, edit);
    if (!decision.ok) {
      say(decision.reason, true);
      return;
    }
    this.send(edit);
  }

  /** Sends one edit as the command that writes it. `exec` reloads this pane through its own hook. */
  private send(edit: GenEdit): void {
    if (this.slug === '') return;
    const command = commandFor(this.slug, edit);
    void exec(command.id, command.props);
  }
}

/** Where the header's Add… menu opens, in the canvas's own coordinates. */
const ADD_MENU_AT: readonly [number, number] = [40, 40];

function describe(button: { description?: string }, description: string): void {
  button.description = description;
}

// -------------------------------------------------------------------------
// The rows inside a node
// -------------------------------------------------------------------------

const ROW_STYLE = 'display: flex; align-items: center; gap: 4px; padding: 1px 4px;';
const LABEL_STYLE =
  'flex: 0 0 auto; min-width: 46px; color: var(--mist); overflow: hidden; white-space: nowrap;';
const FIELD_STYLE =
  'flex: 1 1 auto; min-width: 0; font: inherit; color: var(--paper); padding: 1px 4px; ' +
  'background: var(--ink-sunken); border: 1px solid var(--ink-line); border-radius: 3px;';
const BUTTON_STYLE =
  'flex: 1 1 auto; font: inherit; color: var(--paper); padding: 1px 4px; ' +
  'background: var(--ink-raised); border: 1px solid var(--ink-line); border-radius: 3px;';

/**
 * Builds the editable rows inside one node's frame. Every built-in type declares string and
 * boolean props only, so one builder covers all of them; a value is written through
 * `gengraph.setProp`, which reads the text back through the node's own property.
 */
function buildNodeUI(node: GenNode, body: Container): void {
  const root = document.createElement('div');
  root.style.cssText = 'display: flex; flex-direction: column; gap: 2px; padding: 2px 0;';

  const slotProp = genNodeSpec(node.def.typeName)?.slotProp;
  for (const key of nodePropKeys(node)) {
    // An input carrying a link reads its value from upstream, so its default is no longer editable.
    if (!(key in node.props) && (node.inputs[key]?.edges.length ?? 0) > 0) continue;

    const prop = nodePropTarget(node, key);
    if (prop === undefined) continue;
    // Standing an output up is `gengraph.setActiveOutput`, which stands its rivals down at the same
    // time, and there is no edit for turning one off.
    const row =
      slotProp !== undefined && key === 'active'
        ? activeRow(node, prop, body)
        : valueRow(node, key, prop, body);
    root.appendChild(row);
  }

  if (root.childElementCount > 0) body.shadow.appendChild(root);
}

function valueRow(node: GenNode, key: string, prop: ToolProperty, body: Container): HTMLElement {
  const row = document.createElement('div');
  row.style.cssText = ROW_STYLE;

  const label = document.createElement('span');
  label.textContent = prop.uiname || key;
  label.style.cssText = LABEL_STYLE;
  row.appendChild(label);

  const bool = prop.type === PropTypes.BOOL;
  const field = document.createElement('input');
  field.type = bool ? 'checkbox' : 'text';
  field.title = prop.description || `Set this node's ${key}`;
  if (bool) {
    field.checked = Boolean(prop.getValue());
    field.style.cssText = 'flex: 0 0 auto;';
  } else {
    field.value = String(prop.getValue() ?? '');
    field.style.cssText = FIELD_STYLE;
  }
  // On change rather than on input: each commit is a command and a reload of the whole file.
  field.addEventListener('change', () => {
    raise(body, { op: 'setProp', node: node.id, key, value: bool ? field.checked : field.value });
  });
  stopOwnEvents(field);
  row.appendChild(field);

  return row;
}

function activeRow(node: GenNode, prop: ToolProperty, body: Container): HTMLElement {
  const row = document.createElement('div');
  row.style.cssText = ROW_STYLE;

  const on = Boolean(prop.getValue());
  const button = document.createElement('button');
  button.textContent = on ? 'Active output' : 'Make active';
  button.disabled = on;
  button.style.cssText = BUTTON_STYLE;
  button.style.opacity = on ? '0.6' : '1';
  button.title = on
    ? 'This is already the output a run evaluates for its slot'
    : 'Make this the output a run evaluates, standing down the others on the same slot';
  button.addEventListener('click', () => raise(body, { op: 'setActiveOutput', node: node.id }));
  stopOwnEvents(button);
  row.appendChild(button);

  return row;
}

/**
 * Stops the events a control inside a node frame must not let past it. The screen keymap is a
 * bubble-phase window listener, so an unstopped `/` opens the palette, and an unstopped press
 * starts dragging the node the control sits in.
 */
function stopOwnEvents(control: HTMLElement): void {
  control.addEventListener('keydown', (event) => event.stopPropagation());
  control.addEventListener('pointerdown', (event) => event.stopPropagation());
}

/** Hands an edit to the view that owns the frame these rows were built into. */
function raise(body: Container, edit: GenEdit): void {
  let at: { parentWidget?: unknown } | undefined = body as unknown as { parentWidget?: unknown };
  while (at !== undefined) {
    if (at instanceof GenGraphView) {
      at.onGenEdit?.(edit);
      return;
    }
    at = at.parentWidget as { parentWidget?: unknown } | undefined;
  }
}

// The registry is the renderer's own, so it is filled here rather than by the pane's first read.
// `createUI` is the only hook a frame calls from the node itself, and it is read off the prototype
// during the frame's own build, so the rows are installed by patching the twelve classes rather
// than by assigning to a frame after the view has made it.
registerGenNodes();
for (const cls of genNodeTypes().values()) {
  const patched = cls as unknown as { prototype: { createUI: unknown } };
  patched.prototype.createUI = function (this: GenNode, body: Container): void {
    buildNodeUI(this, body);
  };
}

// The pane's subject is the shared selection, so it remembers only the pin `registerEditor` splices
// in from the `pins` field this editor declares.
registerEditor(GenGraphEditor, 'vn.GenGraphEditor');

/** The written value a property holds, or nothing where it holds something no command carries. */
function genValue(value: unknown): GenPropValue | undefined {
  const kind = typeof value;
  return kind === 'string' || kind === 'number' || kind === 'boolean'
    ? (value as GenPropValue)
    : undefined;
}

/**
 * The edit one write on a node's row is. Ticking `active` on an output stands the rivals claiming
 * its slot down at the same time, which is what `setActiveOutput` does; unticking has no such edit
 * behind it, so it is written as the plain property change the author asked for.
 */
function editFor(watch: PropWatch, key: string, value: GenPropValue): GenEdit {
  const slotProp = genNodeSpec(watch.node.def.typeName)?.slotProp;
  if (slotProp !== undefined && key === 'active' && value === true) {
    return { op: 'setActiveOutput', node: watch.node.id };
  }

  return { op: 'setProp', node: watch.subject, key, value };
}

/** The node an acknowledgement says the edit created, where it says one. */
function createdNode(data: unknown): GraphId | undefined {
  if (typeof data !== 'object' || data === null) return undefined;
  const node = (data as { node?: unknown }).node;
  return typeof node === 'string' || typeof node === 'number' ? node : undefined;
}

/** The level a layout remembered, or nothing for a layout from before levels or a bad string. */
function readDescent(text: string): HeldDescent | undefined {
  if (text === '') return undefined;
  try {
    const parsed = JSON.parse(text) as { slug?: unknown; descent?: unknown };
    if (typeof parsed.slug !== 'string' || !Array.isArray(parsed.descent)) return undefined;
    const descent: DescentEntry[] = [];
    for (const entry of parsed.descent as { nodeId?: unknown; into?: unknown }[]) {
      const id = entry.nodeId;
      if (typeof id !== 'string' && typeof id !== 'number') return undefined;
      descent.push({ nodeId: id, into: entry.into === 'definition' ? 'definition' : 'instance' });
    }
    return { slug: parsed.slug, descent };
  } catch {
    return undefined;
  }
}

